"""Synthetic corpora: labelled telemetry we own outright.

The reason this exists is licensing, not convenience. SKAB — the obvious benchmark, and the
one every measured result in ADR-0021 came from — is GPLv3, so it cannot ship inside a
repository headed for a commercial track. Without something to replace it, a researcher who
clones this repository gets a harness with one 300-row corpus, which is a demo, not a
benchmark.

A generator solves that completely: **anomalies injected by construction *are* the labels**,
so there is no annotation step, no third-party data, and no licence question. It also does
things a fixed dataset cannot — arbitrary size, controllable difficulty, and fault shapes
chosen to exercise specific detector behaviour rather than whatever a testbed happened to do.

Three fault shapes, chosen because they separate detectors that a single shape would rank
identically:

- ``spike``  — a short, violent excursion. Any threshold catches it; it exists as the floor.
- ``drift`` — a slow ramp that ends far from normal but is never locally sudden. A fixed
  threshold catches it only at the end (so: latency), and a baseline-relative detector
  should do better.
- ``stuck`` — the sensor freezes at a plausible value. The reading is *in range the whole
  time*, so a threshold detector cannot see it at all. This is the shape that distinguishes
  "compares to normal" from "compares to a constant".

The output is a bundle (``bundle.py``), written once and committed, so loading it at
benchmark time is a file read rather than a re-run of this code — the same treatment as the
committed team3 artifact (ADR-0012), and for the same reason: generated inputs must be
*fixed*, or every benchmark silently measures a different dataset.
"""

import math
from collections.abc import Iterator, Sequence
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta
from enum import StrEnum
from pathlib import Path

import numpy as np
import pandas as pd

from iotshield.eval.corpus import Case, Corpus, to_stub_csv, write_bundle
from iotshield.eval.truth import GroundTruth, Incident

EPOCH = datetime(2026, 1, 1, 0, 0, 0, tzinfo=UTC)
"""A fixed start instant: generated corpora must not change when the clock does."""

SAMPLE_SECONDS = 1
CHANNELS = ("Pressure", "Temperature", "Vibration")
ASSET_ID = "synthetic-rig"
LICENCE = "CC0-1.0 (generated by iotshield; no third-party data)"
PROVENANCE = "iotshield.eval.generate — synthetic, reproducible from the seed below"


class FaultKind(StrEnum):
    SPIKE = "spike"
    DRIFT = "drift"
    STUCK = "stuck"


@dataclass(frozen=True)
class Recipe:
    """One synthetic recording: how long, what fault, where."""

    name: str
    rows: int
    kind: FaultKind | None
    fault_start: int = 0
    fault_length: int = 0
    seed: int = 0


# Channel scales are chosen so a *fixed absolute threshold* around 80 is a meaningful rule
# on this rig — that is what makes `stub_threshold` a fair baseline here rather than a
# detector mis-parameterized for the data, and it is what lets each fault shape teach its
# intended lesson (see the module docstring).
_NORMAL = {
    "Pressure": (45.0, 1.0),
    "Temperature": (75.0, 0.8),
    "Vibration": (0.05, 0.004),
}
_THRESHOLD_HINT = 80.0


def _baseline(rng: np.random.Generator, rows: int) -> dict[str, np.ndarray]:
    """Independent normal channels, each with its own scale."""
    return {name: rng.normal(mean, spread, rows) for name, (mean, spread) in _NORMAL.items()}


def _apply_fault(series: dict[str, np.ndarray], recipe: Recipe) -> None:
    """Inject the fault in place. The affected span *is* the answer key."""
    if recipe.kind is None:
        return
    start, end = recipe.fault_start, recipe.fault_start + recipe.fault_length
    span = slice(start, end)
    length = recipe.fault_length

    if recipe.kind is FaultKind.SPIKE:
        # A violent excursion, peaking mid-span and well past any sane threshold. The floor:
        # every detector should catch this, so a detector that misses it is broken.
        shape = np.sin(np.linspace(0.0, math.pi, length))
        series["Pressure"][span] += 50.0 * shape
        series["Vibration"][span] += 0.08 * shape
    elif recipe.kind is FaultKind.DRIFT:
        # A slow ramp that ends past the threshold but is never locally sudden. A fixed rule
        # catches it only once it crosses — so this shape is where *latency* separates
        # detectors that a hit/miss score would tie.
        series["Temperature"][span] += np.linspace(0.0, 9.0, length)
    elif recipe.kind is FaultKind.STUCK:
        # The sensor freezes at its last plausible value: in range the entire time, so a
        # fixed threshold is structurally blind. Only a detector that models *normal* —
        # variance, or a baseline — can see it. This is the discriminating shape.
        series["Pressure"][span] = series["Pressure"][start]


def _case(recipe: Recipe) -> Case:
    rng = np.random.default_rng(recipe.seed)
    series = _baseline(rng, recipe.rows)
    _apply_fault(series, recipe)

    timestamps = [EPOCH + timedelta(seconds=SAMPLE_SECONDS * i) for i in range(recipe.rows)]
    frame = pd.DataFrame({channel: series[channel] for channel in CHANNELS}).round(6)
    incidents = (
        []
        if recipe.kind is None
        else [
            Incident(
                start=timestamps[recipe.fault_start],
                end=timestamps[recipe.fault_start + recipe.fault_length - 1],
            )
        ]
    )
    return Case(
        name=recipe.name,
        inputs=[to_stub_csv(frame, timestamps, ASSET_ID)],
        truth=GroundTruth.from_incidents(timestamps, incidents),
    )


def _recipes() -> Iterator[Recipe]:
    """The shipped corpus: three fault shapes x three recordings, plus two clean ones.

    Deliberately more than one recording per shape — a single example per shape would let a
    detector look good or bad by luck, and per-case variance is one of the things the harness
    exists to show (a mean hides the 3-of-16 pattern SKAB revealed).
    """
    rows = 900
    for index, kind in enumerate(FaultKind):
        for repeat in range(3):
            seed = 1000 + index * 10 + repeat
            start = 300 + repeat * 60
            yield Recipe(
                name=f"{kind.value}-{repeat}",
                rows=rows,
                kind=kind,
                fault_start=start,
                fault_length=120 + repeat * 30,
                seed=seed,
            )
    for repeat in range(2):
        yield Recipe(name=f"clean-{repeat}", rows=rows, kind=None, seed=2000 + repeat)


def build(recipes: Sequence[Recipe] | None = None) -> Corpus:
    """Build the synthetic corpus in memory (deterministic: same recipes, same bytes)."""
    chosen = list(recipes) if recipes is not None else list(_recipes())
    faults = sum(1 for recipe in chosen if recipe.kind is not None)
    return Corpus(
        name="synthetic",
        description=(
            f"Synthetic rig telemetry: {len(chosen)} recordings, {faults} injected faults "
            "(spike / drift / stuck) + clean baselines"
        ),
        cases=[_case(recipe) for recipe in chosen],
        provenance=PROVENANCE,
        licence=LICENCE,
    )


def write(directory: Path) -> Corpus:
    """Generate and write the bundle. Idempotent — same input, same bytes on disk."""
    corpus = build()
    write_bundle(directory, corpus)
    return corpus
