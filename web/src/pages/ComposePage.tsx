/**
 * Compose & run a pipeline, as a four-step wizard: Data → Detection → Alerts & output → Review.
 *
 * The wizard changes how the choices are *presented*, never what is sent: state lives here,
 * once, and every step edits it; `buildSpec` turns it into the same `PipelineSpec` the single-
 * page form sent, the same live validation guards it, and the same receipt follows a run.
 * The current step rides in the URL (`?step=`), so a refresh or a shared link lands on it —
 * clamped to the first step whose prerequisites are not yet met, because a step cannot be
 * meaningfully shown before the ones it builds on.
 *
 * Step 1 can also start from a **scenario** (`/samples/manifest.json`, generated by
 * `scripts/make_sample_data.py`): it fills every step at once and lands on Review, and the
 * Review step shows what that scenario is tested to produce.
 */
