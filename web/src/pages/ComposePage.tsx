const STEPS = ["Data", "Detection", "Alerts & output", "Review & run"] as const;
type StepNumber = 1 | 2 | 3 | 4;

const samplesKey = ["samples", "manifest"] as const;

function Stepper({
  current,
  reachable,
  done,
  onGo,
}: {
  readonly current: StepNumber;
  readonly reachable: (step: StepNumber) => boolean;
  readonly done: (step: StepNumber) => boolean;
  readonly onGo: (step: StepNumber) => void;
}) {
  return (
    <ol className="mb-8 grid grid-cols-2 gap-2 sm:grid-cols-4" aria-label="Wizard steps">
      {STEPS.map((title, index) => {
        const step = (index + 1) as StepNumber;
        const active = step === current;
        const complete = done(step) && step < current;
        return (
          <li key={title}>
            <button
              type="button"
              data-testid={`step_${step}`}
              aria-current={active ? "step" : undefined}
              disabled={!reachable(step)}
              onClick={() => onGo(step)}
              className={cn(
                "flex w-full items-center gap-2 rounded-md border px-3 py-2 text-left text-sm transition-colors disabled:cursor-not-allowed disabled:opacity-50",
                active ? "border-accent bg-accent-soft text-accent" : "border-line bg-surface text-dim hover:bg-raised",
              )}
            >
              <span
                className={cn(
                  "flex h-6 w-6 shrink-0 items-center justify-center rounded-full border text-xs font-semibold",
                  active ? "border-accent bg-accent text-accent-ink" : complete ? "border-success text-success" : "border-line",
                )}
              >
                {complete ? <Check className="h-3.5 w-3.5" aria-hidden /> : step}
              </span>
              <span className="truncate font-medium">{title}</span>
            </button>
          </li>
        );
      })}
    </ol>
  );
}

function ScenarioPicker({
  scenarios,
  loading,
  onPick,
}: {
  readonly scenarios: readonly Scenario[];
  readonly loading: string | null;
  readonly onPick: (scenario: Scenario) => void;
}) {
  if (scenarios.length === 0) return null;
  return (
    <Section
      title="Start from a scenario"
      description="Fills every step with sample data and the detectors that suit it, then takes you to Review. You can still change anything before running."
    >
      <div className="grid gap-3 md:grid-cols-2 xl:grid-cols-3">
        {scenarios.map((scenario) => (
          <Card key={scenario.id} className="flex flex-col gap-2 p-4">
            <p className="text-sm font-semibold text-ink">{scenario.title}</p>
            <p className="caption flex-1">{scenario.description}</p>
            <p className="text-2xs text-muted">
              {scenario.samples.length} source{scenario.samples.length === 1 ? "" : "s"} ·{" "}
              {scenario.detectors.length} detector{scenario.detectors.length === 1 ? "" : "s"} · expects{" "}
              {scenario.expected.alerts} alert{scenario.expected.alerts === 1 ? "" : "s"}
            </p>
            <Button
              size="sm"
              data-testid={`scenario_${scenario.id}`}
              disabled={loading !== null}
              onClick={() => onPick(scenario)}
            >
              {loading === scenario.id ? "Loading…" : "Use this scenario"}
            </Button>
          </Card>
        ))}
      </div>
    </Section>
  );
}

function Footer({
  step,
  canNext,
  blocker,
  onBack,
  onNext,
}: {
  readonly step: StepNumber;
  readonly canNext: boolean;
  readonly blocker: string | null;
  readonly onBack: () => void;
  readonly onNext: () => void;
}) {
  return (
    <div className="mt-8 flex items-center justify-between gap-4 border-t border-line pt-4">
      <Button variant="ghost" data-testid="wizard_back" disabled={step === 1} onClick={onBack}>
        ← Back
      </Button>
      <div className="flex items-center gap-3">
        {!canNext && blocker ? <p className="caption">{blocker}</p> : null}
        {step < 4 ? (
          <Button variant="primary" data-testid="wizard_next" disabled={!canNext} onClick={onNext}>
            Next: {STEPS[step as 1 | 2 | 3]} →
          </Button>
        ) : null}
      </div>
    </div>
  );
}

function ComposeWizard({ catalogue }: { readonly catalogue: ModulesResponse }) {
  const normalizers = React.useMemo(() => byName(catalogue.normalizers), [catalogue]);
  const detectorCatalogue = React.useMemo(() => byName(catalogue.detectors), [catalogue]);
  const engines = React.useMemo(() => byName(catalogue.alert_engines), [catalogue]);
  const sinks = React.useMemo(() => byName(catalogue.sinks), [catalogue]);
  const manifest = useQuery({ queryKey: samplesKey, queryFn: fetchManifest, staleTime: Infinity });
  const library: SampleManifest = manifest.data ?? { samples: [], scenarios: [] };

  // Preselection happens exactly once, when this component mounts with the catalogue.
  const [sources, setSources] = React.useState<SourceRow[]>(() => [newSource(normalizers)]);
  const [detectors, setDetectors] = React.useState<DetectorRow[]>(() => {
    const produced = new Set(
      normalizers.find((item) => item.name === newSource(normalizers).normalizer)?.produces ?? [],
    );
    return [newDetector(detectorCatalogue, produced, true)];
  });
  const [engine, setEngine] = React.useState<string>(() => engines[0]?.name ?? "");
  const [engineParams, setEngineParams] = React.useState<ParamValues>(() => initialValues(engines[0]?.params));
  const [selectedSinks, setSelectedSinks] = React.useState<string[]>(() =>
    sinks.some((item) => item.name === "postgres") ? ["postgres"] : sinks.slice(0, 1).map((item) => item.name),
  );
  const [sinkParams, setSinkParams] = React.useState<Record<string, ParamValues>>(() =>
    Object.fromEntries(sinks.map((item) => [item.name, initialValues(item.params)])),
  );
  // The scenario last applied, and the exact spec + inputs it produced: its promised counts
  // are only shown while what will run is still exactly that.
  const [scenario, setScenario] = React.useState<{ scenario: Scenario; fingerprint: string } | null>(null);
  const [loadingScenario, setLoadingScenario] = React.useState<string | null>(null);
  const [scenarioError, setScenarioError] = React.useState<string | null>(null);

  const produced = React.useMemo(
    () =>
      new Set(sources.flatMap((source) => normalizers.find((item) => item.name === source.normalizer)?.produces ?? [])),
    [sources, normalizers],
  );

  const spec = React.useMemo(
    () =>
      buildSpec(
        { sources, detectors, engine, engineParams, sinks: selectedSinks, sinkParams },
        catalogue,
      ),
    [sources, detectors, engine, engineParams, selectedSinks, sinkParams, catalogue],
  );
  const inputs: SourceInput[] = sources.map((source, index) => ({
    content: source.content,
    origin: source.fileName ?? `source-${index + 1}`,
  }));
  const fingerprint = JSON.stringify({ spec, inputs });
  const pristineScenario = scenario !== null && scenario.fingerprint === fingerprint ? scenario.scenario : null;

  const untrained = detectors
    .map((row, index) => ({ row, index }))
    .filter(({ row }) => {
      const module = detectorCatalogue.find((item) => item.name === row.name);
      return module !== undefined && !fitted(module, row.params);
    });

  // --- step gating ---------------------------------------------------------------------------
  const emptySource = sources.findIndex((source) => source.content.trim().length === 0);
  const blockers: Record<StepNumber, string | null> = {
    1:
      sources.length === 0
        ? "Add at least one source."
        : emptySource >= 0
          ? `Source ${emptySource + 1} needs content — pick a sample, upload a file or paste records.`
          : null,
    2:
      detectors.length === 0
        ? "Pick at least one detector to continue."
        : untrained.length > 0
          ? `${untrained[0]?.row.name} has no fitted artifact; name one or choose another detector.`
          : null,
    3: selectedSinks.length === 0 ? "Pick at least one sink so results have somewhere to go." : null,
    4: null,
  };
  const ok = (step: StepNumber) => blockers[step] === null;
  const reachable = (step: StepNumber) => ([1, 2, 3, 4] as const).filter((s) => s < step).every(ok);

  const [params, setParams] = useSearchParams();
  const requested = Math.min(4, Math.max(1, Number.parseInt(params.get("step") ?? "1", 10) || 1)) as StepNumber;
  const firstBlocked = ([1, 2, 3] as const).find((s) => !ok(s));
  const step = (firstBlocked !== undefined && requested > firstBlocked ? firstBlocked : requested) as StepNumber;
  const go = (next: StepNumber) =>
    setParams(
      (current) => {
        const updated = new URLSearchParams(current);
        updated.set("step", String(next));
        return updated;
      },
      { replace: false },
    );

  const validation = useValidation(spec);
  const run = useMutation({ mutationFn: () => pipelineApi.run(spec, inputs) });
  const settling = validation.pending || validation.stale;
  const canRun = ok(1) && ok(2) && ok(3) && (validation.result?.ok ?? false) && !settling && !run.isPending;
  const wrotePostgres = selectedSinks.includes("postgres");

  const applyScenario = async (picked: Scenario) => {
    setLoadingScenario(picked.id);
    setScenarioError(null);
    try {
      const chosen = picked.samples.map((id) => library.samples.find((sample) => sample.id === id));
      const texts = await Promise.all(chosen.map((sample) => (sample ? fetchSampleText(sample) : "")));
      const nextSources = chosen.map((sample, index) =>
        sample ? sourceFromSample(sample, texts[index] ?? "", normalizers) : newSource(normalizers),
      );
      const nextDetectors = picked.detectors.map((entry) => detectorFromScenario(entry, detectorCatalogue));
      const nextEngine = engines.find((item) => item.name === picked.alert_engine.name);
      const nextEngineParams = {
        ...initialValues(nextEngine?.params),
        ...Object.fromEntries(Object.entries(picked.alert_engine.params).map(([k, v]) => [k, String(v)])),
      };
      setSources(nextSources);
      setDetectors(nextDetectors);
      setEngine(picked.alert_engine.name);
      setEngineParams(nextEngineParams);
      run.reset();
      const nextSpec = buildSpec(
        {
          sources: nextSources,
          detectors: nextDetectors,
          engine: picked.alert_engine.name,
          engineParams: nextEngineParams,
          sinks: selectedSinks,
          sinkParams,
        },
        catalogue,
      );
      const nextInputs = nextSources.map((source, index) => ({
        content: source.content,
        origin: source.fileName ?? `source-${index + 1}`,
      }));
      setScenario({ scenario: picked, fingerprint: JSON.stringify({ spec: nextSpec, inputs: nextInputs }) });
      go(4);
    } catch (cause) {
      setScenarioError(`Could not load the scenario: ${describeError(cause)}`);
    } finally {
      setLoadingScenario(null);
    }
  };

  const replaceAt = <T,>(rows: readonly T[], index: number, next: T) =>
    rows.map((row, position) => (position === index ? next : row));

  return (
    <div>
      <Stepper current={step} reachable={reachable} done={ok} onGo={go} />

      {step === 1 ? (
        <div className="space-y-8">
          <ScenarioPicker scenarios={library.scenarios} loading={loadingScenario} onPick={(s) => void applyScenario(s)} />
          {scenarioError ? <Notice tone="error">{scenarioError}</Notice> : null}
          {manifest.isError ? (
            <Notice tone="warning">Sample data is unavailable ({describeError(manifest.error)}); upload or paste your own.</Notice>
          ) : null}
          <Section
            title={library.scenarios.length > 0 ? "…or build your own: input sources" : "Input sources"}
            description="One source per file/format; each is routed to its normalizer and the events are pooled."
          >
            <RowCount
              label="source"
              count={sources.length}
              max={MAX_SOURCES}
              testId="compose_n"
              onChange={(count) =>
                setSources((rows) =>
                  count <= rows.length
                    ? rows.slice(0, count)
                    : [...rows, ...Array.from({ length: count - rows.length }, () => newSource(normalizers))],
                )
              }
            />
            <div className="space-y-4">
              {sources.map((source, index) => (
                <SourceCard
                  key={index}
                  index={index}
                  row={source}
                  normalizers={normalizers}
                  samples={library.samples}
                  onChange={(next) => setSources((rows) => replaceAt(rows, index, next))}
                  onRemove={
                    sources.length > 1 ? () => setSources((rows) => rows.filter((_, position) => position !== index)) : null
                  }
                />
              ))}
            </div>
          </Section>
        </div>
      ) : null}

      {step === 2 ? (
        <Section
          title="Detectors"
          description="One row per detector instance. The same adapter may appear more than once — that is how you run two presets (e.g. a fan-out and an exfiltration rule) at once. Detectors your sources can feed are listed first."
        >
          <RowCount
            label="detector"
            count={detectors.length}
            max={MAX_DETECTORS}
            testId="compose_det_n"
            onChange={(count) =>
              setDetectors((rows) =>
                count <= rows.length
                  ? rows.slice(0, count)
                  : [
                      ...rows,
                      ...Array.from({ length: count - rows.length }, () => newDetector(detectorCatalogue, produced, false)),
                    ],
              )
            }
          />
          <div className="space-y-3">
            {detectors.map((row, index) => (
              <DetectorCard
                key={index}
                index={index}
                row={row}
                detectors={detectorCatalogue}
                produced={produced}
                onChange={(next) => setDetectors((rows) => replaceAt(rows, index, next))}
                onRemove={
                  detectors.length > 1
                    ? () => setDetectors((rows) => rows.filter((_, position) => position !== index))
                    : null
                }
              />
            ))}
          </div>
          {untrained.map(({ row, index }) => (
            <Notice key={index} tone="warning">
              <b>{row.name}</b> has no fitted artifact, so the run will be refused before it judges
              anything. Name one in its parameters, or choose a detector that is ready to run. The
              chain check cannot see this — it never builds the detector.
            </Notice>
          ))}
        </Section>
      ) : null}

      {step === 3 ? (
        <div className="space-y-8">
          <Section title="Alert engine" description="Turns detections into a ranked, explained queue of alerts.">
            <Field label="Alert engine" htmlFor="compose_engine" className="max-w-md">
              <Select
                id="compose_engine"
                data-testid="compose_engine"
                options={engines.map((item) => item.name)}
                value={engine}
                onChange={(event) => {
                  const name = event.target.value;
                  setEngine(name);
                  setEngineParams(initialValues(engines.find((item) => item.name === name)?.params));
                }}
              />
            </Field>
            <Collapsible label={`${engine} parameters`}>
              <ParamFields
                params={engines.find((item) => item.name === engine)?.params}
                values={engineParams}
                idPrefix={`eng_${engine}`}
                onChange={(name, value) => setEngineParams((values) => ({ ...values, [name]: value }))}
              />
            </Collapsible>
          </Section>
          <Section title="Result sinks">
            <MultiSelect
              label="Sinks"
              options={sinks.map((item) => item.name)}
              value={selectedSinks}
              onValueChange={setSelectedSinks}
              hint="Where results go. The 'postgres' store is what the Triage view reads."
            />
            <div className="space-y-2">
              {selectedSinks.map((name) => (
                <Collapsible key={name} label={`${name} parameters`}>
                  <ParamFields
                    params={sinks.find((item: SinkInfo) => item.name === name)?.params}
                    values={sinkParams[name] ?? {}}
                    idPrefix={`sink_${name}`}
                    onChange={(param, value) =>
                      setSinkParams((values) => ({ ...values, [name]: { ...(values[name] ?? {}), [param]: value } }))
                    }
                  />
                </Collapsible>
              ))}
            </div>
          </Section>
        </div>
      ) : null}

      {step === 4 ? (
        <div className="space-y-8">
          <Section title="Your pipeline">
            <Card className="divide-y divide-line">
              <div className="p-4">
                <p className="field-label">Sources</p>
                <ul className="mt-1 space-y-1 text-sm">
                  {sources.map((source, index) => (
                    <li key={index}>
                      <span className="font-mono text-xs">{source.fileName ?? `source-${index + 1}`}</span>
                      <span className="text-muted">
                        {" "}
                        → {source.normalizer} ({source.format}) ·{" "}
                        {source.content.split("\n").filter((line) => line.trim()).length.toLocaleString("en-US")} lines
                      </span>
                    </li>
                  ))}
                </ul>
              </div>
              <div className="p-4">
                <p className="field-label">Detectors</p>
                <ul className="mt-1 space-y-1 text-sm">
                  {detectors.map((row, index) => {
                    // The closed-vocabulary choices (lane, preset, artifact) the row holds, defaults
                    // included: the request omits a default, so reading it would show two `rules`
                    // rows and hide which lane the first one judges.
                    const choices = (detectorCatalogue.find((item) => item.name === row.name)?.params ?? [])
                      .filter((param) => (param.choices?.length ?? 0) > 0 && String(row.params[param.name] ?? "") !== "")
                      .map((param) => `${param.name}: ${String(row.params[param.name])}`);
                    const changed = Object.entries(spec.detectors[index]?.params ?? {})
                      .filter(([key]) => !choices.some((choice) => choice.startsWith(`${key}:`)))
                      .map(([key, value]) => `${key}: ${String(value)}`);
                    const shown = [...choices, ...changed];
                    return (
                      <li key={index}>
                        {row.name}
                        {shown.length > 0 ? <span className="text-xs text-muted"> — {shown.join(", ")}</span> : null}
                      </li>
                    );
                  })}
                </ul>
              </div>
              <div className="grid gap-4 p-4 sm:grid-cols-2">
                <div>
                  <p className="field-label">Alert engine</p>
                  <p className="text-sm">
                    {spec.alert_engine.name}
                    {Object.keys(spec.alert_engine.params).length > 0 ? (
                      <span className="font-mono text-xs text-muted"> {JSON.stringify(spec.alert_engine.params)}</span>
                    ) : null}
                  </p>
                </div>
                <div>
                  <p className="field-label">Sinks</p>
                  <p className="text-sm">{selectedSinks.join(", ")}</p>
                </div>
              </div>
            </Card>
            {pristineScenario ? (
              <Notice tone="info" title={`Scenario: ${pristineScenario.title}`}>
                Tested to produce {pristineScenario.expected.events} events,{" "}
                {pristineScenario.expected.malformed} malformed, {pristineScenario.expected.detections} detections and{" "}
                {pristineScenario.expected.alerts} alerts.
              </Notice>
            ) : null}
          </Section>

          <Section title="Validate & run">
            {/* While settling, the previous verdict is withheld rather than dimmed: a dimmed
                green badge is still a green badge to anyone scanning the page. */}
            {settling ? (
              <Spinner label="Checking the chain…" />
            ) : (
              <>
                {validation.error !== null ? (
                  <Notice tone="error">Validation request failed: {validation.error}</Notice>
                ) : null}
                {validation.result?.issues.map((issue, index) => (
                  <Notice key={index} tone={issue.level === "error" ? "error" : "warning"}>
                    [{issue.stage}] {issue.message}
                  </Notice>
                ))}
                {validation.result !== null && validation.result.ok && validation.result.issues.length === 0 ? (
                  <Notice tone="success">Chain is compatible.</Notice>
                ) : null}
              </>
            )}

            <div className="flex items-center gap-3">
              <Button variant="primary" data-testid="compose_run" disabled={!canRun} onClick={() => run.mutate()}>
                Run pipeline
              </Button>
              {run.isPending ? <Spinner label="Running…" /> : null}
            </div>

            {run.isError ? <Notice tone="error">Run failed: {describeError(run.error)}</Notice> : null}

            {run.isSuccess ? (
              <div className="space-y-4 pt-2">
                <Notice tone="success">Run complete.</Notice>
                <div className="grid grid-cols-2 gap-3 lg:grid-cols-4">
                  <StatTile label="events" value={run.data.events} />
                  <StatTile label="malformed" value={run.data.malformed} />
                  <StatTile label="detections" value={run.data.detections} />
                  <StatTile label="alerts" value={run.data.alerts} />
                </div>
                {pristineScenario ? (
                  (["events", "malformed", "detections", "alerts"] as const).every(
                    (key) => run.data[key] === pristineScenario.expected[key],
                  ) ? (
                    <Notice tone="success">Matches what the scenario is tested to produce.</Notice>
                  ) : (
                    <Notice tone="warning">
                      Differs from what the scenario is tested to produce — the detectors or data on this
                      server may not match the sample library.
                    </Notice>
                  )
                ) : null}
                {run.data.warnings.map((warning, index) => (
                  <Notice key={index} tone="warning">
                    {warning}
                  </Notice>
                ))}
                <p className="caption">Written to: {run.data.destinations.join(", ") || "nothing"}</p>
                {/* A receipt, not a results view: the ranked, explained alerts live on the read
                    plane. Triage reads the postgres store only. */}
                {run.data.alerts > 0 && wrotePostgres ? (
                  <Notice tone="info">
                    {run.data.alerts} alert(s) written — see them ranked and explained under{" "}
                    <strong>Monitor → Triage</strong>.
                  </Notice>
                ) : null}
                {run.data.malformed > 0 && wrotePostgres ? (
                  <p className="caption">
                    {run.data.malformed} malformed record(s) were quarantined — see <strong>Monitor → Data health</strong>.
                  </p>
                ) : null}
                {!wrotePostgres ? (
                  <p className="caption">No postgres sink selected — results are in the chosen sink(s), not Triage.</p>
                ) : null}
              </div>
            ) : null}
          </Section>
        </div>
      ) : null}

      <Footer
        step={step}
        canNext={ok(step)}
        blocker={blockers[step]}
        onBack={() => go(Math.max(1, step - 1) as StepNumber)}
        onNext={() => go(Math.min(4, step + 1) as StepNumber)}
      />
    </div>
  );
}

export function ComposePage() {
  const modules = useModules();

  return (
    <>
      <PageHeader
        title="Compose & run a pipeline"
        description="Four steps: choose the data, the detectors, where results go, then review and run. Results appear under Monitor → Triage."
      />
      {modules.isPending ? <Spinner label="Loading the adapter catalogue…" /> : null}
      {modules.isError ? (
        <ErrorState
          title="Pipeline API unreachable"
          detail={<>{describeError(modules.error)}. Start it with:</>}
          command="IOTSHIELD_DATABASE_URL=sqlite:///demo.db python -m iotshield.api.control"
          onRetry={() => void modules.refetch()}
        />
      ) : null}
      {modules.isSuccess ? (
        modules.data.normalizers.length === 0 ||
        modules.data.detectors.length === 0 ||
        modules.data.alert_engines.length === 0 ||
        modules.data.sinks.length === 0 ? (
          <Notice tone="error">The Pipeline API reports no adapters — nothing to compose.</Notice>
        ) : (
          <ComposeWizard catalogue={modules.data} />
        )
      ) : null}
    </>
  );
}
